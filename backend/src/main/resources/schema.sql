CREATE TABLE IF NOT EXISTS users (
 user_id BIGINT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, nickname VARCHAR(30) NOT NULL UNIQUE,
 bio VARCHAR(200), role VARCHAR(10) NOT NULL DEFAULT 'USER', status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(role IN ('USER','ADMIN')), CHECK(status IN ('ACTIVE','SUSPENDED'))
);
CREATE TABLE IF NOT EXISTS posts (
 post_id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(user_id),
 content VARCHAR(2000) NOT NULL, post_type VARCHAR(12) NOT NULL DEFAULT 'NORMAL', external_url VARCHAR(2048),
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(post_type IN ('NORMAL','PROMOTION')), CHECK(status IN ('ACTIVE','HIDDEN','DELETED'))
);
CREATE TABLE IF NOT EXISTS post_media (
 media_id BIGINT AUTO_INCREMENT PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(post_id),
 storage_key VARCHAR(500) NOT NULL UNIQUE, sort_order TINYINT NOT NULL,
 mime_type VARCHAR(30) NOT NULL, byte_size INT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(post_id,sort_order), CHECK(sort_order BETWEEN 1 AND 4)
);
CREATE TABLE IF NOT EXISTS comments (
 comment_id BIGINT AUTO_INCREMENT PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(post_id),
 user_id BIGINT NOT NULL REFERENCES users(user_id), content VARCHAR(500) NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, CHECK(status IN ('ACTIVE','DELETED'))
);
CREATE TABLE IF NOT EXISTS post_likes (
 user_id BIGINT NOT NULL REFERENCES users(user_id), post_id BIGINT NOT NULL REFERENCES posts(post_id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,post_id)
);
CREATE TABLE IF NOT EXISTS follows (
 follower_id BIGINT NOT NULL REFERENCES users(user_id), following_id BIGINT NOT NULL REFERENCES users(user_id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(follower_id,following_id), CHECK(follower_id <> following_id)
);
CREATE TABLE IF NOT EXISTS hashtags (hashtag_id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(50) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS post_hashtags (
 post_id BIGINT NOT NULL REFERENCES posts(post_id), hashtag_id BIGINT NOT NULL REFERENCES hashtags(hashtag_id),
 PRIMARY KEY(post_id,hashtag_id)
);
CREATE TABLE IF NOT EXISTS reports (
 report_id BIGINT AUTO_INCREMENT PRIMARY KEY, reporter_id BIGINT NOT NULL REFERENCES users(user_id),
 post_id BIGINT NOT NULL REFERENCES posts(post_id), reason VARCHAR(300) NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'OPEN', reviewed_by BIGINT REFERENCES users(user_id),
 resolution_note VARCHAR(300), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, reviewed_at TIMESTAMP,
 UNIQUE(reporter_id,post_id), CHECK(status IN ('OPEN','RESOLVED','REJECTED'))
);
CREATE INDEX IF NOT EXISTS idx_posts_feed ON posts(status,created_at,post_id);
CREATE INDEX IF NOT EXISTS idx_posts_user ON posts(user_id,status,created_at);
CREATE INDEX IF NOT EXISTS idx_comments_post ON comments(post_id,status);
CREATE INDEX IF NOT EXISTS idx_follows_target ON follows(following_id);
